#!/usr/bin/env python3
"""Reads the decomp's REL module layout (config/G4BE08) and writes what the 360 build needs to link the overlays statically.

usage: gen_modules.py <project root> <out dir>
  <out>/modules.cmake   RE4_MODULES, RE4_MOD_<name>_SRCS (absolute paths), RE4_MODULE_SOURCES (all of them)
  <out>/rel_table.cpp   g_relTable: module id -> <name>__prolog / __epilog / __unresolved (the module's renamed entry points)

On the GameCube each REL was linked on its own, so the stage / weapon / enemy modules define the same global names. Here every
module is partially linked into one object whose symbols are made local except its three entry points (CMakeLists.txt).
"""
import importlib.util, json, os, re, sys

root, out = os.path.abspath(sys.argv[1]), os.path.abspath(sys.argv[2])
os.makedirs(out, exist_ok=True)
ver = os.path.join(root, 'config', 'G4BE08')
spec = importlib.util.spec_from_file_location('modules', os.path.join(ver, 'modules.py'))
mm = importlib.util.module_from_spec(spec); spec.loader.exec_module(mm)
units = getattr(mm, 'UNITS', {})
cfg = open(os.path.join(ver, 'config.yml')).read()
names = re.findall(r'^\s+name:\s*(\S+)\s*$', cfg, re.M)
excl = [re.compile(l.strip()) for l in open(os.path.join(root, 'tools/xenon/excluded.txt')) if l.strip() and not l.startswith('#')]

def excluded(rel):
    return any(r.search(rel) for r in excl)

mods = []   # (name, id, [abs sources])
for name in names:
    srcs = []
    for unit, _first, *src in units.get(name, [(f'{name}/{name}.cpp', None)]):
        rel = 'src/' + (src[0] if src and src[0] else unit)
        if excluded(rel) or not os.path.exists(os.path.join(root, rel)):
            continue
        p = os.path.join(root, rel)
        if p not in srcs:
            srcs.append(p)
    if not srcs:
        continue
    mid = json.load(open(os.path.join(ver, 'modules', name, 'rel.json')))['module_id']
    mods.append((name, mid, srcs))

with open(os.path.join(out, 'modules.cmake'), 'w') as f:
    f.write('# generated by tools/xenon/gen_modules.py\n')
    f.write('set(RE4_MODULES %s)\n' % ' '.join(n for n, _, _ in mods))
    allsrc = sorted({s for _, _, ss in mods for s in ss})
    f.write('set(RE4_MODULE_SOURCES\n%s)\n' % ''.join('    "%s"\n' % s for s in allsrc))
    for n, _, ss in mods:
        f.write('set(RE4_MOD_%s_SRCS\n%s)\n' % (n, ''.join('    "%s"\n' % s for s in ss)))

with open(os.path.join(out, 'rel_table.cpp'), 'w') as f:
    f.write('// generated by tools/xenon/gen_modules.py\nextern "C" {\n')
    for n, _, _ in mods:
        for e in ('prolog', 'epilog', 'unresolved'):
            f.write('void %s__%s(void) __attribute__((weak));\n' % (n, e))
    f.write('struct RelEntry { unsigned id; const char* name; void (*prolog)(void); void (*epilog)(void); void (*unresolved)(void); };\n')
    f.write('const RelEntry g_relTable[] = {\n')
    for n, i, _ in mods:
        f.write('    {%d, "%s", %s__prolog, %s__epilog, %s__unresolved},\n' % (i, n, n, n, n))
    f.write('};\nconst int g_relTableCount = %d;\n}\n' % len(mods))
print('modules:', len(mods), 'sources:', len(allsrc))
